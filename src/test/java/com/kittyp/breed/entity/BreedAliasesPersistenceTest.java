package com.kittyp.breed.entity;

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.sql.DriverManager;
import java.time.LocalDateTime;
import java.util.List;

import org.hibernate.SessionFactory;
import org.hibernate.cfg.Configuration;
import org.junit.jupiter.api.Test;
import org.springframework.context.annotation.ClassPathScanningCandidateComponentProvider;
import org.springframework.core.type.filter.AnnotationTypeFilter;

import jakarta.persistence.Entity;

class BreedAliasesPersistenceTest {
    @Test
    void postgresDialectInitializesEntityMappings() throws ClassNotFoundException {
        Configuration configuration = new Configuration();
        var scanner = new ClassPathScanningCandidateComponentProvider(false);
        scanner.addIncludeFilter(new AnnotationTypeFilter(Entity.class));
        for (var definition : scanner.findCandidateComponents("com.kittyp")) {
            configuration.addAnnotatedClass(Class.forName(definition.getBeanClassName()));
        }
        try (SessionFactory factory = configuration
                .setProperty("hibernate.dialect", "org.hibernate.dialect.PostgreSQLDialect")
                .setProperty("hibernate.boot.allow_jdbc_metadata_access", "false")
                .setProperty("jakarta.persistence.database-major-version", "16")
                .setProperty("jakarta.persistence.database-minor-version", "0")
                .setProperty("hibernate.hbm2ddl.auto", "none")
                .buildSessionFactory()) {
        }
    }

    @Test
    void persistsReadsAndUpdatesAliases() throws Exception {
        String url = "jdbc:h2:mem:breed-aliases;DB_CLOSE_DELAY=-1";
        try (var connection = DriverManager.getConnection(url, "sa", "");
                var statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE breed_master (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        species VARCHAR(30) NOT NULL,
                        name VARCHAR(255) NOT NULL,
                        aliases TEXT ARRAY NOT NULL,
                        is_active BOOLEAN NOT NULL,
                        created_at TIMESTAMP NOT NULL,
                        updated_at TIMESTAMP
                    )
                    """);
        }

        try (SessionFactory factory = new Configuration()
                .addAnnotatedClass(Breed.class)
                .setProperty("hibernate.connection.driver_class", "org.h2.Driver")
                .setProperty("hibernate.connection.url", url)
                .setProperty("hibernate.connection.username", "sa")
                .setProperty("hibernate.hbm2ddl.auto", "none")
                .buildSessionFactory()) {
            Breed breed = new Breed();
            breed.setSpecies("DOG");
            breed.setName("German Shepherd Dog");
            breed.setAliases(List.of("GSD", "Alsatian, German Shepherd"));
            breed.setCreatedAt(LocalDateTime.now());
            factory.inTransaction(session -> session.persist(breed));

            factory.inTransaction(session -> {
                Breed saved = session.find(Breed.class, breed.getId());
                assertEquals(List.of("GSD", "Alsatian, German Shepherd"), saved.getAliases());
                saved.setAliases(List.of("German Shepherd", "GSD"));
            });
            factory.inTransaction(session -> {
                Breed saved = session.find(Breed.class, breed.getId());
                assertEquals(List.of("German Shepherd", "GSD"), saved.getAliases());
                saved.setAliases(List.of());
            });
            factory.inTransaction(session ->
                    assertEquals(List.of(), session.find(Breed.class, breed.getId()).getAliases()));
        }
    }

    @Test
    void newBreedDefaultsToEmptyAliases() {
        assertEquals(List.of(), new Breed().getAliases());
    }
}
